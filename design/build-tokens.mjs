// Generates web CSS variables from tokens.json. Android/iOS generators are added when those apps are scaffolded.
import { readFileSync, writeFileSync } from "node:fs";

const t = JSON.parse(readFileSync(new URL("./tokens.json", import.meta.url), "utf8"));
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(" ");
const block = (vars) => Object.entries(vars).map(([k, v]) => `  --${k}: ${rgb(v)};`).join("\n");

const css = `/* Generated by design/build-tokens.mjs from design/tokens.json. Do not edit. */
:root {
${block(t.light)}
}
:root.dark {
${block(t.dark)}
}
@media (prefers-color-scheme: dark) {
  :root:not(.light) {
${block(t.dark).replace(/^/gm, "  ")}
  }
}
`;
writeFileSync(new URL("../web/src/styles/tokens.css", import.meta.url), css);
console.log("tokens.css written");
